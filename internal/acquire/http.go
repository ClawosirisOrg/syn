package acquire

import (
	"context"
	"errors"
	"io"
	"net/http"
	"strings"
	"time"
)

// HTTPClient pins the HTTPS GitHub API origin, denies redirects and keeps its
// credential out of URLs, errors and records. Injected transports must be trusted.
type HTTPClient struct {
	token  string
	client http.Client
}

func NewHTTPClient(token string, transport http.RoundTripper) (*HTTPClient, error) {
	if strings.TrimSpace(token) == "" || strings.ContainsAny(token, "\r\n") {
		return nil, errors.New("invalid GitHub credential")
	}
	if transport == nil {
		transport = http.DefaultTransport
	}
	return &HTTPClient{token: token, client: http.Client{Transport: transport, Timeout: 10 * time.Second, CheckRedirect: func(*http.Request, []*http.Request) error { return http.ErrUseLastResponse }}}, nil
}
func (h *HTTPClient) GET(ctx context.Context, p string, limit int64) ([]byte, error) {
	if h == nil || ctx == nil || limit < 1 || limit > maxBody*2+maxMetadata || !validAPIPath(p) {
		return nil, errors.New("invalid GitHub GET request")
	}
	req, e := http.NewRequestWithContext(ctx, http.MethodGet, "https://api.github.com"+p, nil)
	if e != nil {
		return nil, errors.New("invalid GitHub GET request")
	}
	req.Header.Set("Authorization", "Bearer "+h.token)
	req.Header.Set("Accept", "application/vnd.github+json")
	resp, e := h.client.Do(req)
	if e != nil {
		return nil, errors.New("GitHub GET failed")
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		return nil, errors.New("GitHub GET refused")
	}
	if resp.ContentLength > limit {
		return nil, errors.New("oversized GitHub response")
	}
	b, e := io.ReadAll(io.LimitReader(resp.Body, limit+1))
	if e != nil {
		return nil, errors.New("GitHub response read failed")
	}
	if int64(len(b)) > limit {
		return nil, errors.New("oversized GitHub response")
	}
	return b, nil
}

// Only shapes generated by Acquire are valid: no arbitrary URLs or methods.
func validAPIPath(p string) bool {
	if strings.ContainsAny(p, "\\%#") || strings.Contains(p, "..") || strings.Contains(p, "//") {
		return false
	}
	pathname, query, hasQuery := strings.Cut(p, "?")
	seg := strings.Split(pathname, "/")
	if len(seg) < 4 || seg[0] != "" || seg[1] != "repos" || !validRepo(seg[2]+"/"+seg[3]) {
		return false
	}
	if len(seg) == 4 {
		return !hasQuery
	}
	if len(seg) >= 6 && seg[4] == "branches" && !hasQuery {
		return validBranch(strings.Join(seg[5:], "/"))
	}
	if len(seg) > 5 && seg[4] == "contents" && hasQuery && validFile(strings.Join(seg[5:], "/")) {
		return strings.HasPrefix(query, "ref=") && sha.MatchString(strings.TrimPrefix(query, "ref="))
	}
	return false
}
